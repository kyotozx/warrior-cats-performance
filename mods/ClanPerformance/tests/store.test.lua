local store=dofile('mods/ClanPerformance/Scripts/store.lua')
local path=os.tmpname()
os.remove(path)
local function cleanup()
 for _,suffix in ipairs({'','.previous','.tmp'})do os.remove(path..suffix)end
end
local ok,why=pcall(function()
 local s=store.new(path)
 assert(s.load()==nil,'Missing preferences must not create defaults on disk')
 s.save({schema=1,label='Original',counter=false})
 assert(s.load().label=='Original')
 s.save({schema=1,label='Low',counter=true})
 assert(s.load().label=='Low')
 assert(store.new(path..'.previous').load().label=='Original','Previous committed state must survive rotation')
 assert(os.remove(path))
 assert(s.load().label=='Original','Interrupted rename must recover the previous file')
 local f=assert(io.open(path,'wb'));f:write('{broken');f:close()
 assert(not pcall(s.load),'Corrupt primary must fail closed instead of silently losing the recovery baseline')
 f=assert(io.open(path,'wb'));f:write(string.rep('x',65537));f:close()
 assert(not pcall(s.load),'Oversized input must be rejected')
end)
cleanup()
assert(ok,why)
print('PASS: real preference writes, rotation, interrupted rename, corruption and size limit')
