local base='mods/ClanPerformance/Scripts/'
local O=dofile(base..'options.lua');local C=dofile(base..'controller.lua');local count=0
local function test(n,f)f();count=count+1;print('PASS '..n)end
local function fixture(loaded)
 local original=O.copy(O.presets[1].values);original.scale=100;original.cap=90
 local live=O.copy(original);local saved=loaded;local now=100;local ops={};local failApply=false;local failStore=false;local failNative=false
 local adapter={read=function()return O.copy(live)end,apply=function(v)
  ops[#ops+1]='apply';live=O.copy(v);if failApply then failApply=false;live.scale=100;error('native failed')end
 end,save=function()ops[#ops+1]='native-save';if failNative then failNative=false;error('native save failed')end end}
 local store={load=function()return saved end,save=function(v)ops[#ops+1]='store';if failStore then failStore=false;error('disk failed')end;saved=O.copy(v)end}
 local api=C.new(adapter,store,function()return now end)
 return api,original,function()return live,saved,ops end,function(v)now=v end,
  function(kind)if kind=='apply'then failApply=true elseif kind=='store'then failStore=true else failNative=true end end,adapter,store
end
test('startup does not change first-run settings',function()
 local a,o,read=fixture();assert(a.start());local live,s,ops=read();assert(O.equal(live,o)and #ops==0);assert(a.status().error==nil)
end)
test('baseline persisted before apply and preview needs confirmation',function()
 local a,o,read=fixture();assert(a.start());assert(a.preview(O.presets[2].values,'Low'))
 local live,s,ops=read();assert(ops[1]=='store'and ops[2]=='apply');assert(O.equal(s.original,o));assert(s.pending and not s.desired)
 assert(a.confirm());live,s=read();assert(not s.pending and s.label=='Low'and O.equal(live,s.desired))
end)
test('preview timeout restores previous live state',function()
